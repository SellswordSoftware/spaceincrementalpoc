import assert from 'node:assert/strict';
import test from 'node:test';
import { advanceTicks, balance, definitions, deserializeGame, serializeGame } from '../src/core/index.js';
import { runPrestigeScenario } from '../scenarios/prestige.js';

test('the network fully resets into the Insight shop and rebuilds faster with permanent modifiers',()=>{
  const {game,firstReport:report,report:prestige,reset,preview}=runPrestigeScenario();
  assert.equal(prestige.award,5);
  assert.equal(preview.losses.course?.progress,20);
  assert.equal(preview.losses.program?.progress,20);
  assert.equal(reset.insight.phase,'shop');
  assert.equal(reset.insight.points,5);
  assert.deepEqual(reset.resources,balance.startingStocks);
  assert.deepEqual(reset.purchases,{});
  assert.equal(reset.population.total,0);
  assert.equal(reset.course,null);
  assert.deepEqual(reset.science,{publications:0,program:null});
  assert.deepEqual(reset.journal,['moon']);
  assert.equal(reset.clock.tick,0);
  assert.equal(prestige.shopRestored,true);
  assert.ok(prestige.secondRunSeconds<prestige.firstRunSeconds);
  assert.ok(prestige.secondAcademySeconds<prestige.firstAcademySeconds);
  assert.equal(game.state.clock.campaignIndex,2);
  assert.equal(game.state.insight.points,0);
  assert.equal(game.state.insight.totalEarned,5);
  assert.equal(report.instantKnowledge,2);
  assert.equal(report.processingRateAfter,report.processingRate);
  assert.equal(report.afterJupiter,report.beforeJupiter*2);
  assert.equal(report.actionAfter,report.actionBefore*2);
  assert.ok(report.afterTelescope>report.beforeTelescope);
  assert.equal(report.afterWorkstation,report.beforeWorkstation*2);
  assert.equal(report.nextAfterFundraiser,'research');
  assert.equal(report.people,4);
  assert.equal(report.teacherCourseSeconds,report.firstCourseSeconds/2);
  assert.equal(report.observingWhileTeaching,report.observingBeforeTeaching);
  assert.equal(report.firstStudySeconds,60);
  assert.equal(report.scientistStudySeconds,30);
  assert.equal(report.publications,2);
  assert.equal(report.grants,2);
  assert.equal(report.fundingAfterGrants,report.fundingBeforeGrants+4);
  assert.equal(report.rates.D,report.observingBeforeStudies);
  const before=game.state.resources.D;
  advanceTicks(game,definitions,balance,240);
  assert.ok(game.state.resources.D>before);
  assert.equal('data' in game.state,false);
  assert.equal(game.state.science.publications,2);
  assert.deepEqual(deserializeGame(serializeGame(game)),game);
});
