import assert from 'node:assert/strict';
import test from 'node:test';
import { advanceTicks, balance, definitions, deserializeGame, serializeGame, dispatch, quoteCommand, getSummary } from '../src/core/index.js';
import { runContinuousProgression } from '../scenarios/progression.js';
import { runSynthesisScenario } from '../scenarios/synthesis.js';
import { runHorizonsScenario } from '../scenarios/horizons.js';
import { runEngineeringScenario } from '../scenarios/engineering.js';
import { runPrestigeScenario } from '../scenarios/prestige.js';

test('the network fully resets into the Insight shop and rebuilds faster with permanent modifiers',()=>{
  const {game,firstReport:report,report:prestige,reset,preview}=runPrestigeScenario();
  assert.ok(prestige.award>=5);
  assert.ok(preview.losses.classrooms>=2);
  assert.ok(preview.losses.researchTeams>=2);
  assert.equal(reset.insight.phase,'shop');
  assert.equal(reset.insight.points,prestige.award);
  assert.deepEqual(reset.resources,balance.startingStocks);
  assert.deepEqual(reset.purchases,{});
  assert.equal(reset.population.total,0);
  assert.deepEqual(reset.academy,{timers:[],remainder:0});
  assert.deepEqual(reset.science,{publications:0,timers:[],remainder:0});
  assert.deepEqual(reset.journal,['moon']);
  assert.equal(reset.clock.tick,0);
  assert.equal(prestige.shopRestored,true);
  assert.ok(prestige.secondRunSeconds<prestige.firstRunSeconds);
  assert.ok(prestige.secondAcademySeconds<prestige.firstAcademySeconds);
  assert.equal(game.state.clock.campaignIndex,2);
  assert.equal(game.state.insight.points,0);
  assert.equal(game.state.insight.totalEarned,5);
  assert.equal(report.instantKnowledge,2);
  assert.equal(report.processingRateAfter,report.processingRate);
  assert.equal(report.afterJupiter,report.beforeJupiter*2);
  assert.equal(report.actionAfter,report.actionBefore*2);
  assert.ok(report.afterTelescope>report.beforeTelescope);
  assert.equal(report.afterWorkstation,report.beforeWorkstation*2);
  assert.equal(report.nextAfterFundraiser,'research');
  assert.ok(report.people>=4);
  assert.equal(report.teacherCourseSeconds,report.firstCourseSeconds);
  assert.equal(report.observingWhileTeaching,report.observingBeforeTeaching);
  assert.equal(report.firstStudySeconds,60);
  assert.equal(report.scientistStudySeconds,60);
  assert.ok(report.publications>=2);
  assert.equal(report.grants,2);
  assert.equal(report.fundingAfterGrants,report.fundingBeforeGrants+4);
  assert.equal(report.rates.D,report.observingBeforeStudies);
  assert.ok(report.classroomBefore[0]>0);
  assert.ok(report.scienceBefore[0]>0);
  assert.deepEqual(report.classroomAfter,[...report.classroomBefore,0]);
  assert.deepEqual(report.scienceAfter,[...report.scienceBefore,0]);
  // Higher rewards must never compress time. No wallet is debited on completion.
  for (const investmentId of ['teaching-methods','science-practice']) {
    const command=/** @type {const} */({type:'buyInvestment',investmentId});
    while (!quoteCommand(game,definitions,balance,command).ok) advanceTicks(game,definitions,balance,4);
    assert.equal(dispatch(game,definitions,balance,command).ok,true);
  }
  const cycle=getSummary(game,definitions,balance);
  assert.equal(cycle.academy.seconds,40);
  assert.equal(cycle.science.seconds,60);
  assert.equal(cycle.academy.reward,1.3125); // 1.25 practice × 1.05 teaching Insight
  const people=game.state.population.total;
  const publications=game.state.science.publications;
  const wallets={...game.state.resources};
  const lanes=game.state.academy.timers.length;
  const teams=game.state.science.timers.length;
  const graduateRemainder=game.state.academy.remainder;
  const publicationRemainder=game.state.science.remainder;
  const before=game.state.resources.D;
  advanceTicks(game,definitions,balance,240);
  assert.ok(game.state.resources.D>before);
  for (const key of /** @type {const} */(['D','F','K','I','X'])) assert.ok(game.state.resources[key]>=wallets[key]);
  // Over 120 seconds each classroom completes three cycles, each team two.
  advanceTicks(game,definitions,balance,240);
  assert.equal(game.state.population.total-people,Math.floor(graduateRemainder+3*lanes*cycle.academy.reward+1e-9));
  assert.equal(game.state.science.publications-publications,Math.floor(publicationRemainder+2*teams*cycle.science.reward+1e-9));
  assert.equal('data' in game.state,false);
  assert.ok(game.state.science.publications>publications);
  assert.deepEqual(deserializeGame(serializeGame(game)),game);
  const {report:engineering}=runEngineeringScenario(game);
  assert.ok(engineering.engineeringRate>0);
  assert.equal(engineering.afterCapacity,engineering.beforeCapacity+48);
  assert.equal(engineering.afterTelescopes,engineering.beforeTelescopes+3);
  assert.equal(engineering.facility,'Mountain observatory');
  assert.equal(engineering.frontierYield,21);
  assert.ok(engineering.afterData>engineering.beforeData);
  assert.ok(engineering.afterScienceReward>engineering.beforeScienceReward);
  assert.equal(engineering.scienceSeconds,60);
  assert.deepEqual(engineering.phasesAfter,engineering.phases);
  assert.deepEqual(deserializeGame(serializeGame(game)),game);
  const {report:horizons}=runHorizonsScenario(game);
  assert.ok(horizons.radioData>horizons.beforeData);
  assert.ok(horizons.orbitalData>0);
  assert.ok(horizons.afterData>horizons.radioData);
  assert.equal(horizons.afterCapacity,horizons.beforeCapacity+180);
  assert.equal(horizons.afterTelescopes,horizons.beforeTelescopes+4);
  assert.equal(horizons.frontierYield,144);
  assert.deepEqual(horizons.orbitalAtCommission,{progress:0,cycles:0,remainder:0});
  assert.deepEqual(horizons.infraredAtCommission,{progress:0,cycles:0,remainder:0});
  assert.equal(horizons.needsOrbitalResult,true);
  assert.ok(horizons.firstOrbit.cycles>=1);
  assert.equal(horizons.noOperatingDrain,true);
  assert.ok(horizons.missions.orbital.cycles>horizons.orbitalAtFlagship.cycles);
  assert.ok(horizons.missions.infrared.cycles>=1);
  assert.equal(horizons.scienceSeconds,60);
  assert.deepEqual(horizons.missionSeconds,[60,60]);
  const restored=deserializeGame(serializeGame(game));
  assert.deepEqual(restored,game);
  advanceTicks(game,definitions,balance,240);
  advanceTicks(restored,definitions,balance,240);
  assert.deepEqual(restored,game); // Mission phases, cycle counts and fractional rewards resume identically.
  const {game:finished,report:synthesis}=runSynthesisScenario(game);
  assert.deepEqual(synthesis.firstAtEstablishment,{progress:0,cycles:0,remainder:0,publicationRemainder:0});
  assert.equal(synthesis.creditsAtEstablishment,0);
  assert.equal(synthesis.creditsBeforeFirstCycle,0);
  assert.ok(Object.values(synthesis.programCycles).every(cycles=>cycles>=1));
  for (const currency of /** @type {const} */(['D','K','E','science'])) assert.ok((synthesis.afterUpgrades[currency]??0)>(synthesis.beforeUpgrades[currency]??0));
  assert.deepEqual(synthesis.programSeconds,[60,60,60]);
  assert.equal(synthesis.finaleSeconds,90);
  assert.equal(synthesis.finaleAtStart,0);
  assert.equal(synthesis.resumed,true);
  assert.equal(synthesis.completedBeforeBoundary,false);
  assert.equal(synthesis.completionEvents,1);
  assert.equal(synthesis.repeatedCompletionEvents,0);
  assert.equal(synthesis.completedProgress,90);
  assert.equal(finished.state.joint.completedAtTick,synthesis.completedAtTick);
  assert.ok(Object.keys(finished.state.joint.programs).length===3);
  assert.deepEqual(deserializeGame(serializeGame(finished)),finished);
  // The resumed game becomes the active run for the reset check.
  game.state=finished.state;
  const permanent=structuredClone(game.state.insight.upgrades);
  assert.equal(dispatch(game,definitions,balance,{type:'beginPrestige'}).ok,true);
  assert.deepEqual(game.state.purchases,{});
  assert.equal(game.state.resources.E,0);
  assert.deepEqual(game.state.missions,{});
  assert.equal(game.state.resources.C,0);
  assert.deepEqual(game.state.joint,{programs:{},finaleProgress:null,completedAtTick:null});
  assert.deepEqual(game.state.journal,['moon']);
  assert.deepEqual(game.state.insight.upgrades,permanent);
  assert.equal(getSummary(game,definitions,balance).observing.current.name,'Backyard observatory');
  assert.deepEqual(deserializeGame(serializeGame(game)),game);
  const {game:continuous,report:curve}=runContinuousProgression();
  assert.equal(continuous.state.insight.totalEarned,0);
  assert.equal(continuous.state.clock.campaignIndex,1);
  assert.ok(continuous.state.joint.completedAtTick!==null);
  assert.ok(curve.milestones.engineering<curve.milestones.academy);
  assert.ok(curve.milestones['permanent-enclosure']<curve.milestones.academy);
  assert.ok(curve.milestones['robotic-dome']>curve.milestones.academy);
  assert.ok(curve.milestones['expanded-observatory']>curve.milestones.photometry);
  assert.ok(curve.milestones['mountain-telescope']>curve.milestones['target-galaxies']);
  assert.deepEqual(deserializeGame(serializeGame(continuous)),continuous);
});
